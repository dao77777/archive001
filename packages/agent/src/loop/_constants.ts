/** 一轮对话里最多"调模型 → 执行工具"几次,防死循环 */
export const MAX_STEPS = 12;

/** 人格与工作环境;与工具集无关,总是同一句 */
const PERSONA = `你是 archive001,一个会调工具的 agent,运行在用户的 macOS 机器上,当前工作目录就是用户的目录。`;

/** 有工具时的行为规则 */
const RULES_WITH_TOOLS = `规则:
- 需要事实就先动手查(用工具),不要凭空猜。
- 每次调用工具后,根据返回结果决定下一步;任务完成后用简洁的中文给出结论。
- 不要执行破坏性命令(删除、覆盖用户数据),除非用户明确要求。`;

/**
 * 没有工具时的约束。
 *
 * ⚠️ 这不是锦上添花:提示词里承诺了工具、`tools` 却是空的,模型会把工具调用**写成正文**
 * (实测:`<tool_call>{"name":"shell",…}</tool_call>`),客户端既执行不了也不会继续 ——
 * 用户看到的就是"卡在调用工具里"。所以工具集为空时必须**明确告知**。
 */
const RULES_WITHOUT_TOOLS = `⚠️ 本次运行**没有任何工具可用**:
- 只能基于对话里已有的信息直接回答;
- 不要输出 <tool_call> / {"name": …} 这类标记,也不要声称你执行过命令或读过文件;
- 需要的信息不在上下文里时,直说"我这边没有工具,拿不到这个信息",并说明你需要什么输入。`;

/** 按本次 `run` 实际拿到的工具集拼系统提示词 —— 提示词不能比真实能力更大。 */
export const systemPromptFor = (toolNames: ReadonlyArray<string>): string =>
  toolNames.length === 0
    ? [PERSONA, RULES_WITHOUT_TOOLS].join("\n\n")
    : [PERSONA, `你可以调用这些工具:${toolNames.join("、")}。`, RULES_WITH_TOOLS].join("\n\n");

